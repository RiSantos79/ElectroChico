function normalize(name: string): string {
  return name
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .trim();
}

export function coordsForCity(city: string): [number, number] | null {
  return PT_CITY_COORDS[normalize(city)] ?? null;
}
